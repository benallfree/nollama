package main

// bench report: one markdown table per metric from saved vps reports, nollama next to Ollama with the winner.
//
//	bench report FILE.json...
//
// A row is one machine and model. The winner column is green when nollama is ahead, red when Ollama is, and yellow
// when they're within 5% of each other. "nollama vs Ollama" is how many times better nollama is on that metric (above
// 1 is better, whichever way the metric runs).

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
)

type reportMetric struct {
	title  string
	about  string
	unit   string
	higher bool // higher is better
	get    func(VPSRow) float64
}

var reportMetrics = []reportMetric{
	{"Writing speed", "Tokens written per second, after the short prompt.", "tok/s", true,
		func(r VPSRow) float64 { return r.Short.Decode }},
	{"Reading speed, long prompt", "Prompt tokens read per second, for the 590-token prompt.", "tok/s", true,
		func(r VPSRow) float64 { return r.Long.Prefill }},
	{"Reading speed, short prompt", "Prompt tokens read per second, for the 35-token prompt.", "tok/s", true,
		func(r VPSRow) float64 { return r.Short.Prefill }},
	{"First token, model loaded", "Time to the first token of the long prompt, with the model already loaded.", "s", false,
		func(r VPSRow) float64 { return r.Long.TTFT }},
	{"First token, cold start", "Time from a fresh start, with the model file not in the page cache, to the first token of the short prompt.", "s", false,
		func(r VPSRow) float64 { return r.ColdTTFT }},
	{"First token, warm start", "The same, with the model file already in the page cache.", "s", false,
		func(r VPSRow) float64 { return r.WarmTTFT }},
	{"Peak memory", "Highest resident memory of the process holding the model, including the memory-mapped file.", "MB", false,
		func(r VPSRow) float64 { return float64(r.PeakRSSMB) }},
}

func cmdReport(args []string) error {
	var reps []VPSReport
	for _, p := range args {
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		var rep VPSReport
		if err := json.Unmarshal(b, &rep); err != nil {
			return fmt.Errorf("%s: %v", p, err)
		}
		reps = append(reps, rep)
	}
	sort.SliceStable(reps, func(i, j int) bool { return reps[i].System.Label < reps[j].System.Label })
	writeReport(os.Stdout, reps)
	return nil
}

type reportPair struct {
	machine, model string
	ours, theirs   VPSRow
}

func reportPairs(reps []VPSReport) []reportPair {
	var out []reportPair
	for _, rep := range reps {
		machine := machineName(rep.System)
		by := map[string]map[string]VPSRow{}
		var order []string
		for _, r := range rep.Rows {
			if r.Skipped != "" || r.Error != "" {
				continue
			}
			k := r.Model + " " + r.Quant
			if by[k] == nil {
				by[k] = map[string]VPSRow{}
				order = append(order, k)
			}
			by[k][r.Engine] = r
		}
		for _, k := range order {
			ours, ok1 := by[k]["nollama"]
			theirs, ok2 := by[k]["ollama"]
			if ok1 && ok2 {
				out = append(out, reportPair{machine, k, ours, theirs})
			}
		}
	}
	return out
}

func machineName(s System) string {
	cpu := strings.TrimSuffix(s.CPU, " Processor")
	if i := strings.Index(cpu, "("); i >= 0 {
		if j := strings.Index(cpu[i:], ")"); j > 0 {
			cpu = strings.TrimSpace(strings.Split(cpu[i+1:i+j], ",")[0])
		}
	}
	return fmt.Sprintf("%s (%d vCPU, %s)", s.Label, s.VCPUs, cpu)
}

func writeReport(w io.Writer, reps []VPSReport) {
	if len(reps) == 0 {
		return
	}
	pairs := reportPairs(reps)
	fmt.Fprintf(w, "Generated by `bench report` from %d saved `bench vps` runs, one per machine. Each run wrote %d tokens per measurement and took the median of %d runs, with one thread per vCPU.\n\n",
		len(reps), reps[0].System.Gen, reps[0].System.Runs)
	fmt.Fprintf(w, "| Machine | CPU | Date | nollama commit | Ollama |\n|---|---|---|---|---|\n")
	for _, r := range reps {
		s := r.System
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s |\n", machineName(s), s.CPU, strings.SplitN(s.StartedAt, "T", 2)[0],
			strings.TrimSuffix(s.Nollama, "-dirty")[:min(12, len(s.Nollama))], strings.TrimPrefix(s.Ollama, "ollama version is "))
	}
	fmt.Fprintln(w)
	for _, m := range reportMetrics {
		fmt.Fprintf(w, "### %s\n\n%s ", m.title, m.about)
		if m.higher {
			fmt.Fprintf(w, "Higher is better.\n\n")
		} else {
			fmt.Fprintf(w, "Lower is better.\n\n")
		}
		fmt.Fprintf(w, "| Machine | Model | nollama | Ollama | nollama vs Ollama | Winner |\n|---|---|---|---|---|---|\n")
		for _, p := range pairs {
			a, b := m.get(p.ours), m.get(p.theirs)
			if a <= 0 || b <= 0 {
				continue
			}
			ratio := a / b
			if !m.higher {
				ratio = b / a
			}
			win := "🟡 tie"
			switch {
			case ratio > 1.05:
				win = "🟢 nollama"
			case ratio < 1/1.05:
				win = "🔴 Ollama"
			}
			fmt.Fprintf(w, "| %s | %s | %s | %s | %.2f× | %s |\n", p.machine, p.model, fmtVal(a, m.unit), fmtVal(b, m.unit), ratio, win)
		}
		fmt.Fprintln(w)
	}
}

func fmtVal(v float64, unit string) string {
	switch {
	case unit == "s" && v < 1:
		return fmt.Sprintf("%.0f ms", v*1000)
	case unit == "s":
		return fmt.Sprintf("%.1f s", v)
	case unit == "MB":
		return fmt.Sprintf("%.0f MB", v)
	case v < 10:
		return fmt.Sprintf("%.1f %s", v, unit)
	}
	return fmt.Sprintf("%.0f %s", v, unit)
}
